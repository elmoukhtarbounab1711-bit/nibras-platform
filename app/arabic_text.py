def darija_to_msa(text: str) -> str:
    """يحوّل كلمات الدارجة المغربية إلى الفصحى القانونية إن أمكن.

    لا يجرّب تحويل كامل النص (معرّك) بل يستبدل الكلمات المعروفة فقط
    ويُعيد النص مع تطبيعه. مفيد لتحسين دقة البحث عند استخدام أسئلة بالدارجة.
    """
    if not text:
        return text
    normalized = normalize_arabic(text)
    words = normalized.split()
    out = []
    for w in words:
        msa = DARIJA_TO_MSA.get(w)
        if msa:
            out.append(normalize_arabic(msa))
        else:
            out.append(w)
    return " ".join(out)
