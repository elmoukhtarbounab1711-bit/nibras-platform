def expand_query(query: str) -> str:
    """توسعة استعلام البحث: تضيف مصطلحات قانونية مرتبطة بكلمات الدارجة.

    مثال: "كيفاش نطلاق" → "كيفاش نطلاق طلاق تطليق فسخ زواج"
    """
    query_lower = query.lower()
    expansions = []
    for darija_key, legal_terms in QUERY_EXPANSION_MAP.items():
        if darija_key in query_lower:
            expansions.append(legal_terms)
    if expansions:
        return query + " " + " ".join(expansions)
    return query


def classify_query(query: str) -> list[str]:
    """تصنيف السؤال حسب المجال القانوني.

    يعيد قائمة بمفاتيح المواضيع المرتبطة (مرتبة من الأكثر تطابقاً).
    """
    query_lower = query.lower()
    scores = {}
    for topic_key, topic in DAILY_LIFE_TOPICS.items():
        score = 0
        all_keywords = topic["keywords_ar"] + topic["keywords_darija"]
        for kw in all_keywords:
            if kw.lower() in query_lower:
                score += 2
        for kw in topic.get("common_queries", []):
            if any(w in query_lower for w in kw.split() if len(w) > 2):
                score += 1
        if score > 0:
            scores[topic_key] = score
    return [k for k, _ in sorted(scores.items(), key=lambda x: -x[1])]


def topic_context(topic_keys: list[str]) -> str:
    """يبني سياقًا قانونيًا موجزًا للمواضيع المحددة.

    يُستخدم لإثراء البرومبت حتى وإن لم تُعثر نتائج بحث مباشرة — يعطي
    الذكاء الاصطناعي خريطة عامة للمجال القانوني المتعلق بالسؤال.
    """
    if not topic_keys:
        return ""
    sections = []
    for key in topic_keys[:3]:  # أقصى 3 مواضيع
        topic = DAILY_LIFE_TOPICS.get(key)
        if not topic:
            continue
        laws = "\n".join(f"  - {l}" for l in topic["key_laws"][:6])
        sections.append(
            f"المجال: {topic['title']}\n"
            f"النصوص المرجعية الرئيسية:\n{laws}"
        )
    return "\n\n".join(sections)
