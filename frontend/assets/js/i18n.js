// FR: حمول كسول — يُحمَّل فقط عند تبديل المستخدم إلى الفرنسية
let _frDict = null;
let _loadingFr = null;

async function _loadFr() {
  if (_frDict) return _frDict;
  if (_loadingFr) return _loadingFr;
  _loadingFr = import("./i18n-fr.js").then((m) => { _frDict = m.FR; return _frDict; });
  return _loadingFr;
}

export function tr(key) {
  const lang = (localStorage.getItem("nibras_lang") || "ar");
  const dict = lang === "fr" ? (_frDict || {}) : AR;
  let v = dict;
  for (const part of key.split(".")) {
    if (v == null) return key;
    v = v[part];
  }
  return v ?? key;
}

export const currentLang = () => (localStorage.getItem("nibras_lang") || "ar");

export async function setLang(lang) {
  localStorage.setItem("nibras_lang", lang);
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";
  if (lang === "fr") await _loadFr();
  document.title = lang === "ar" ? "نبراس — المنصة القانونية المغربية"
    : "Nibras — La plateforme juridique marocaine";
  document.dispatchEvent(new CustomEvent("nibras:lang"));
}

export function applyLang() {
  return setLang(currentLang());
}

